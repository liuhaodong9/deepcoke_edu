# -*- coding: utf-8 -*-
"""
LLM 答题输出的中文术语兜底替换。

理由:LLM 在 prompt 里收到术语规范表(literature_qa/service.py 的 _TERM_GUIDE
和 generation/answer_generator.py 的 system prompt),但 qwen3:8b 指令遵守率不是
100%,会漏 5-10% 案例。这里做确定性替换作为第二层防线。

排序约定:**长 key 必须在前**,避免短 key 吃掉长 key 前缀
(例:"镜质体反射率" 必须在 "镜质体" 之前;"塑性区域" 必须在 "塑性区" 之前)。
"""

# (错误词, 学界惯用词)
# 注意顺序,长 key 在前
TERM_FIX = [
    # 显微组分
    ("镜质体反射率", "镜质组反射率"),
    ("镜质体", "镜质组"),
    ("惰性成分", "惰质组"),
    ("惰性组分", "惰质组"),
    ("惰组分", "惰质组"),
    ("惰质体", "惰质组"),
    ("壳质体", "壳质组"),

    # 胶质层 / 热塑性区间(顺序敏感:长 key 先匹配)
    ("塑性区域", "热塑性区间"),
    ("塑性层", "胶质层"),
    ("塑性区", "胶质层"),
    ("塑性体", "胶质体"),

    # 煤 / 焦炭质量
    ("焦化煤", "炼焦煤"),
    ("焦炭反应率", "焦炭反应性"),
    ("焦炭活性", "焦炭反应性"),
    ("反应后焦强度", "反应后强度"),
    ("半焦炭", "半焦"),
    ("焦粉", "焦末"),
    ("焦灰", "焦末"),

    # 流变 / 工艺参数
    ("流体性", "流动度"),
    ("焦化压强", "焦化压力"),

    # 孔结构
    ("微孔率", "微孔"),
    ("微孔度", "微孔"),
]


def fix_terms(text: str) -> str:
    """对 LLM 输出做术语规范化兜底替换。piece-level 或 full-text 均可调用。"""
    if not text:
        return text
    for wrong, right in TERM_FIX:
        if wrong in text:
            text = text.replace(wrong, right)
    return text
